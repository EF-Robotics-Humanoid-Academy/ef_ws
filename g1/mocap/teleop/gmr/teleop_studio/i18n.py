def translate(language: str, key: str, **kwargs: Any) -> str:
    """Return a formatted UI string, falling back to Chinese for missing keys."""
    language_strings = _TRANSLATIONS.get(language, _TRANSLATIONS[DEFAULT_LANGUAGE])
